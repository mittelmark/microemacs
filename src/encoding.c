/*
 * meUtf8ValidSeqLen - Validate and return UTF-8 sequence length.
 * Checks lead byte AND continuation bytes (0x80-0xBF).
 * Returns actual sequence length if valid UTF-8, or 1 if not valid
 * (treat as single CP1252 byte).
 */
int meUtf8ValidSeqLen(const unsigned char *s) {
    unsigned char c = s[0];
    int seqlen, i;
    if(c < 0x80) return 1;
    if((c & 0xE0) == 0xC0) seqlen = 2;
    else if((c & 0xF0) == 0xE0) seqlen = 3;
    else if((c & 0xF8) == 0xF0) seqlen = 4;
    else return 1;
    for(i = 1; i < seqlen; i++) {
        if((s[i] & 0xC0) != 0x80) return 1;
    }
    return seqlen;
}

