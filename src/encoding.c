int meConvString(meConv *conv, const unsigned char *in, size_t in_len,
                 unsigned char *out, size_t out_len) {
    size_t in_pos = 0;
    size_t out_pos = 0;
    while (in_pos < in_len && out_pos < out_len) {
        int result = meConvChar(conv, in + in_pos, in_len - in_pos,
                                out + out_pos, out_len - out_pos);
        if (result < 0) return -1;
        int consumed;
        switch (conv->from) {
            case ME_ENC_UTF8: {
                int32_t cp;
                consumed = utf8_decode_one(in + in_pos, in_len - in_pos, &cp);
                if (consumed == 0) return -1;
                break;
            }
            default:
                consumed = 1;
                break;
        }
        in_pos += consumed;
        out_pos += result;
    }
    return (int)out_pos;
}

meEncoding meDetectBOM(const unsigned char *data, size_t len) {
    if(len >= 3 && data[0] == 0xEF && data[1] == 0xBB && data[2] == 0xBF)
        return ME_ENC_UTF8;
    if(len >= 2 && data[0] == 0xFE && data[1] == 0xFF)
        return ME_ENC_UTF8;  /* UTF-16 BE - treat as UTF-8 for now */
    if(len >= 2 && data[0] == 0xFF && data[1] == 0xFE)
        return ME_ENC_UTF8;  /* UTF-16 LE - treat as UTF-8 for now */
    return ME_ENC_UTF8;
}

