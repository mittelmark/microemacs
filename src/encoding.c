static int utf8_decode_one(const unsigned char *in, size_t in_len, int32_t *cp) {
    if (in_len == 0) return 0;
    unsigned char c = in[0];
    if (c < 0x80) {
        *cp = c;
        return 1;
    } else if ((c & 0xE0) == 0xC0) {
        if (in_len < 2) return 0;
        if ((in[1] & 0xC0) != 0x80) return 0;
        *cp = ((int32_t)(c & 0x1F) << 6) | (in[1] & 0x3F);
        return 2;
    } else if ((c & 0xF0) == 0xE0) {
        if (in_len < 3) return 0;
        if ((in[1] & 0xC0) != 0x80 || (in[2] & 0xC0) != 0x80) return 0;
        *cp = ((int32_t)(c & 0x0F) << 12) | ((int32_t)(in[1] & 0x3F) << 6) | (in[2] & 0x3F);
        return 3;
    } else if ((c & 0xF8) == 0xF0) {
        if (in_len < 4) return 0;
        if ((in[1] & 0xC0) != 0x80 || (in[2] & 0xC0) != 0x80 || (in[3] & 0xC0) != 0x80) return 0;
        *cp = ((int32_t)(c & 0x07) << 18) | ((int32_t)(in[1] & 0x3F) << 12) |
              ((int32_t)(in[2] & 0x3F) << 6) | (in[3] & 0x3F);
        return 4;
    }
    return 0;
}

static int utf8_encode_one(int32_t cp, unsigned char *out) {
    if (cp < 0x80) {
        out[0] = (unsigned char)cp;
        return 1;
    } else if (cp < 0x800) {
        out[0] = (unsigned char)(0xC0 | (cp >> 6));
        out[1] = (unsigned char)(0x80 | (cp & 0x3F));
        return 2;
    } else if (cp < 0x10000) {
        out[0] = (unsigned char)(0xE0 | (cp >> 12));
        out[1] = (unsigned char)(0x80 | ((cp >> 6) & 0x3F));
        out[2] = (unsigned char)(0x80 | (cp & 0x3F));
        return 3;
    } else if (cp < 0x200000) {
        out[0] = (unsigned char)(0xF0 | (cp >> 18));
        out[1] = (unsigned char)(0x80 | ((cp >> 12) & 0x3F));
        out[2] = (unsigned char)(0x80 | ((cp >> 6) & 0x3F));
        out[3] = (unsigned char)(0x80 | (cp & 0x3F));
        return 4;
    }
    return 0;
}

