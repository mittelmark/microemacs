int meUtf8CharSize(const unsigned char *c) {
    if (*c < 0x80) return 1;
    if ((*c & 0xE0) == 0xC0) return 2;
    if ((*c & 0xF0) == 0xE0) return 3;
    if ((*c & 0xF8) == 0xF0) return 4;
    return 0;
}

int meUtf8IsValid(const unsigned char *data, size_t len) {
    size_t i = 0;
    while (i < len) {
        int sz = meUtf8CharSize(data + i);
        if (sz == 0) return 0;
        for (int j = 1; j < sz; j++) {
            if (i + j >= len || (data[i + j] & 0xC0) != 0x80)
                return 0;
        }
        i += sz;
    }
    return 1;
}

int32_t meUtf8Decode(const unsigned char *c) {
    int32_t cp;
    utf8_decode_one(c, 4, &cp);
    return cp;
}

size_t meUtf8Encode(int32_t codepoint, unsigned char *out) {
    return (size_t)utf8_encode_one(codepoint, out);
}

