static int unicode_to_iso8859_2_byte(int32_t cp) {
    /* ISO-8859-2: bytes 0xA0-0xFF map to specific Unicode codepoints */
    if (cp < 0x80) return (int)cp;
    if (cp >= 0xA0 && cp <= 0xFF) {
        /* Simple direct mapping for most characters */
        int idx = cp - 0x80;
        if (iso8859_2_to_unicode[idx] == cp) return (int)cp;
    }
    /* Search the table for reverse mapping */
    for (int i = 0; i < 128; i++) {
        if (iso8859_2_to_unicode[i] == (uint16_t)cp) return (i + 0x80);
    }
    return -1;
}

